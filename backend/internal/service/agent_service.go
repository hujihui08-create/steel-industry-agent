// GeneratePlan analyses the user message and generates an execution plan via LLM.
// It first retrieves long-term memories for the user and injects them as context
// into the planner prompt so the agent can leverage cross-session preferences.
func (s *AgentService) GeneratePlan(
	ctx context.Context,
	userID uint,
	userMessage string,
	history []model.ChatMessage,
	availableTools []openai.Tool,
) (*AgentPlan, error) {
	cfg, cfgErr := s.agentConfigSvc.GetAgentConfig(ctx)
	maxSteps := 5
	if cfgErr == nil && cfg != nil && cfg.MaxSteps > 0 && cfg.MaxSteps <= 10 {
		maxSteps = cfg.MaxSteps
	}

	// Task 7.2: Retrieve long-term memories and build context string.
	var memoryContext string
	if s.memoryRepo != nil {
		memoryContext = s.buildMemoryContext(ctx, userID)
	}

	// Task 22: Semantic memory retrieval — search for similar past conversation
	// summaries using vector similarity before generating the plan.
	var semanticContext string
	if s.vectorRepo != nil && userMessage != "" {
		semanticContext = s.buildSemanticMemoryContext(ctx, userID, userMessage)
	}

	// Build a description of available tools for the planner prompt.
	toolDescriptions := s.buildToolListForPlanner(availableTools)

	// Build planner messages.
	systemContent := agentPlannerPrompt
	if memoryContext != "" {
		systemContent = memoryContext + "\n" + agentPlannerPrompt
	}
	if semanticContext != "" {
		systemContent = semanticContext + "\n" + systemContent
	}
	messages := []openai.ChatCompletionMessage{
		{Role: openai.ChatMessageRoleSystem, Content: systemContent},
		{
			Role:    openai.ChatMessageRoleUser,
			Content: fmt.Sprintf("Available tools:\n%s\n\nUser message: %s\n\nGenerate a JSON plan:", toolDescriptions, userMessage),
		},
	}

	// If history exists, include a summary.
	if len(history) > 0 {
		historySummary := buildHistorySummary(history)
		messages = []openai.ChatCompletionMessage{
			{Role: openai.ChatMessageRoleSystem, Content: systemContent},
			{
				Role:    openai.ChatMessageRoleUser,
				Content: fmt.Sprintf("Conversation history:\n%s\n\nAvailable tools:\n%s\n\nUser message: %s\n\nGenerate a JSON plan:", historySummary, toolDescriptions, userMessage),
			},
		}
	}

	// Call LLM (non-streaming) for the plan.
	resp, err := s.llmAdapter.Chat(ctx, messages)
	if err != nil {
		slog.Warn("planner LLM call failed, using fallback single-step plan", "error", err)
		return s.fallbackPlan(maxSteps), nil
	}

	if len(resp.Choices) == 0 || resp.Choices[0].Message.Content == "" {
		slog.Warn("planner returned empty response, using fallback single-step plan")
		return s.fallbackPlan(maxSteps), nil
	}

	raw := resp.Choices[0].Message.Content
	plan, parseErr := parsePlanJSON(raw)
	if parseErr != nil {
		slog.Warn("planner returned invalid JSON, using fallback single-step plan",
			"raw", raw,
			"error", parseErr,
		)
		return s.fallbackPlan(maxSteps), nil
	}

	// Cap steps to maxSteps.
	if len(plan.Steps) > maxSteps {
		plan.Steps = plan.Steps[:maxSteps]
	}
	plan.MaxSteps = maxSteps
	plan.CreatedAt = time.Now()

	return plan, nil
}

// buildToolListForPlanner creates a human-readable list of tools for the planner prompt.
func (s *AgentService) buildToolListForPlanner(tools []openai.Tool) string {
	if len(tools) == 0 {
		return "(no tools available)"
	}

	var parts []string
	for _, t := range tools {
		if t.Function == nil {
			continue
		}
		desc := t.Function.Description
		if desc == "" {
			desc = "(no description)"
		}
		parts = append(parts, fmt.Sprintf("- %s: %s", t.Function.Name, desc))
	}
	if len(parts) == 0 {
		return "(no tools available)"
	}
	return strings.Join(parts, "\n")
}

// parsePlanJSON attempts to parse LLM output into an AgentPlan.
func parsePlanJSON(raw string) (*AgentPlan, error) {
	raw = strings.TrimSpace(raw)

	// Strip markdown code fences if present.
	if strings.HasPrefix(raw, "```") {
		raw = strings.TrimPrefix(raw, "```json")
		raw = strings.TrimPrefix(raw, "```")
		raw = strings.TrimSuffix(raw, "```")
		raw = strings.TrimSpace(raw)
	}

	var plan AgentPlan
	if err := json.Unmarshal([]byte(raw), &plan); err != nil {
		return nil, fmt.Errorf("parse plan JSON: %w", err)
	}
	return &plan, nil
}

// fallbackPlan generates a single-step fallback plan when the LLM fails.
func (s *AgentService) fallbackPlan(maxSteps int) *AgentPlan {
	return &AgentPlan{
		Steps: []PlanStep{
			{
				Step:     1,
				Intent:   "general",
				ToolName: "",
				Params:   nil,
			},
		},
		MaxSteps:  maxSteps,
		CreatedAt: time.Now(),
	}
}

// buildHistorySummary creates a brief summary of past conversation for the planner.
func buildHistorySummary(history []model.ChatMessage) string {
	const maxHistoryEntries = 6
	start := 0
	if len(history) > maxHistoryEntries {
		start = len(history) - maxHistoryEntries
	}

	var parts []string
	for _, m := range history[start:] {
		role := m.Role
		content := m.Content
		if len(content) > 200 {
			content = content[:200] + "..."
		}
		parts = append(parts, fmt.Sprintf("[%s]: %s", role, content))
	}
	return strings.Join(parts, "\n")
}

// buildMemoryContext retrieves long-term memories for a user and formats them
// as a planner context string. Returns empty string if no memories are found.
// The keys queried align with those set by ChatService.saveMemories.
func (s *AgentService) buildMemoryContext(ctx context.Context, userID uint) string {
	memoryKeys := []string{"last_category", "last_spec", "last_region", "last_query"}
	labelMap := map[string]string{
		"last_category": "上次查询品种",
		"last_spec":     "上次查询规格",
		"last_region":   "上次查询地区",
		"last_query":    "上次查询内容",
	}

	var lines []string
	for _, key := range memoryKeys {
		memories, err := s.memoryRepo.FindByUserAndKey(ctx, userID, key)
		if err != nil || len(memories) == 0 {
			continue
		}
		value := strings.TrimSpace(memories[0].Value)
		if value == "" {
			continue
		}
		label := labelMap[key]
		lines = append(lines, fmt.Sprintf("- %s: %s", label, value))
	}

	if len(lines) == 0 {
		return ""
	}

	return "[用户历史偏好]\n" + strings.Join(lines, "\n")
}

// buildSemanticMemoryContext vectorizes the user's input, searches for similar
// past conversation summaries using pgvector cosine similarity, and formats
// the results as context for the planner prompt.
// Returns an empty string if no similar memories are found or vector search is unavailable.
func (s *AgentService) buildSemanticMemoryContext(ctx context.Context, userID uint, userMessage string) string {
	if s.llmAdapter == nil {
		return ""
	}

	// Step 1: Vectorize the user input.
	embeddings, err := s.llmAdapter.CreateEmbeddings(ctx, "text-embedding-3-small", []string{userMessage})
	if err != nil || len(embeddings) == 0 || len(embeddings[0]) == 0 {
		return ""
	}

	queryVector := float32ArrayToVector(embeddings[0])

	// Step 2: Search for similar past memories.
	memories, err := s.vectorRepo.VectorSearch(ctx, userID, queryVector, 0.75, 5)
	if err != nil || len(memories) == 0 {
		return ""
	}

	// Step 3: Format retrieved memories as context.
	var lines []string
	for _, mem := range memories {
		content := strings.TrimSpace(mem.Content)
		if content == "" {
			continue
		}
		lines = append(lines, fmt.Sprintf("- %s (相似度: %.0f%%)", content, mem.Similarity*100))
	}

	if len(lines) == 0 {
		return ""
	}

	return "[历史相关对话摘要]\n" + strings.Join(lines, "\n")
}

