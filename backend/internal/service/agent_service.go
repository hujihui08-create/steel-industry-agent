// CleanExpiredMemories deletes long-term memory entries that have not been
// accessed within the past 30 days. Returns the number of deleted records.
// This method is intended to be called periodically (e.g. via a scheduled
// task or cron job) to prevent the memories table from growing unbounded.
func (s *AgentService) CleanExpiredMemories(ctx context.Context) (int64, error) {
	return s.memoryRepo.DeleteExpired(ctx, 30*24*time.Hour)
}

// CleanExpiredEmbeddings deletes semantic memory embedding records older than
// 90 days. Returns the number of deleted records. This method is intended to be
// called periodically to prevent the embeddings table from growing unbounded.
func (s *AgentService) CleanExpiredEmbeddings(ctx context.Context) (int64, error) {
	if s.vectorRepo == nil {
		return 0, nil
	}
	return s.vectorRepo.DeleteExpired(ctx, 90*24*time.Hour)
}
