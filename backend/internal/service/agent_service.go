// SubAgent defines the interface for a specialized agent that handles
// domain-specific tasks. Each SubAgent is responsible for executing steps
// that match its domain (e.g. price queries, quotations, tenders).
type SubAgent interface {
	Name() string
	Execute(ctx context.Context, step PlanStep, workMemory map[string]string) (*StepResult, error)
}

// AgentService orchestrates multi-step agent planning, execution, and reflection.
type AgentService struct {
	llmAdapter     *ai.LLMAdapter
	agentConfigSvc *AgentConfigService
	memoryRepo     *repository.AgentMemoryRepository
	vectorRepo     *repository.AgentMemoryVectorRepository
	subAgents      map[string]SubAgent
}

// NewAgentService creates a new AgentService with the required dependencies.
func NewAgentService(
	llmAdapter *ai.LLMAdapter,
	agentConfigSvc *AgentConfigService,
	memoryRepo *repository.AgentMemoryRepository,
	vectorRepo *repository.AgentMemoryVectorRepository,
) *AgentService {
	return &AgentService{
		llmAdapter:     llmAdapter,
		agentConfigSvc: agentConfigSvc,
		memoryRepo:     memoryRepo,
		vectorRepo:     vectorRepo,
	}
}

// RegisterSubAgent adds a SubAgent to the AgentService's registry.
// Multiple calls with the same name will overwrite the previous registration.
func (s *AgentService) RegisterSubAgent(agent SubAgent) {
	if s.subAgents == nil {
		s.subAgents = make(map[string]SubAgent)
	}
	s.subAgents[agent.Name()] = agent
}

// RouteToSubAgent looks up a SubAgent by name. Returns the agent and true if
// found, or nil and false otherwise.
func (s *AgentService) RouteToSubAgent(step PlanStep) (SubAgent, bool) {
	if s.subAgents == nil {
		return nil, false
	}
	agent, ok := s.subAgents[step.SubAgentName]
	return agent, ok
}

