// PlanStep represents a single step in an agent execution plan.
type PlanStep struct {
	Step         int                    `json:"step"`
	Intent       string                 `json:"intent"`
	ToolName     string                 `json:"tool_name"`
	Params       map[string]interface{} `json:"params,omitempty"`
	DependsOn    []int                  `json:"depends_on,omitempty"`
	SubAgentName string                 `json:"sub_agent_name,omitempty"`
}

// AgentPlan is the full execution plan generated by the Planner.
type AgentPlan struct {
	Steps     []PlanStep `json:"steps"`
	MaxSteps  int        `json:"max_steps"`
	CreatedAt time.Time  `json:"created_at"`
}

// StepResult represents the outcome of executing a single step.
type StepResult struct {
	StepIndex int    `json:"step_index"`
	Success   bool   `json:"success"`
	Result    string `json:"result"` // JSON string from tool
	Error     string `json:"error,omitempty"`
	Retries   int    `json:"retries"`
}

// ReflectionResult represents the outcome of reflecting on a step result.
type ReflectionResult struct {
	Status     string `json:"status"` // "ok", "replan", "failed"
	Reason     string `json:"reason,omitempty"`
	Suggestion string `json:"suggestion,omitempty"`
}

// AgentEvent represents a streaming event pushed to the SSE channel.
type AgentEvent struct {
	Type string      `json:"type"`
	Data interface{} `json:"data"`
}

const (
	agentPlannerPrompt = `You are an agent planner for a steel industry assistant. Given a user message, break it down into an ordered list of execution steps.

Each step must specify:
- step: step number (starting from 1)
- intent: short description of what this step does
- tool_name: from the available tools list (use empty string "" if no specific tool is needed)
- params: parameters to pass to the tool
- depends_on: (optional) list of step indices this step depends on
- sub_agent_name: (optional) the name of the specialized sub-agent to handle this step

Rules:
1. Only use tools from the provided list
2. Keep steps minimal and focused
3. If the user request is simple, use 1-2 steps
4. When the task involves a specific domain, set sub_agent_name to the appropriate agent: price/price_trend → 'price_agent', quotation → 'quotation_agent', tender → 'tender_agent', knowledge/search → 'knowledge_agent', alert/convert/weight → 'alert_agent'
5. Return ONLY valid JSON, no other text`
)

