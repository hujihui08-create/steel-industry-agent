// ExecuteStep runs a single plan step by calling the LLM with the step's
// parameters and extracting the tool invocation result.
func (s *AgentService) ExecuteStep(
	ctx context.Context,
	step PlanStep,
	workMemory map[string]string,
	tools []openai.Tool,
) (*StepResult, error) {
	// If no tool is specified, let the caller handle it directly.
	if step.ToolName == "" {
		return &StepResult{
			StepIndex: step.Step,
			Success:   true,
			Result:    "",
		}, nil
	}

	// Resolve parameters: inject any dependency outputs from workMemory.
	params := s.resolveParams(step, workMemory)

	// Build messages for the tool execution.
	systemMsg := openai.ChatCompletionMessage{
		Role:    openai.ChatMessageRoleSystem,
		Content: fmt.Sprintf("You are a steel industry assistant. Execute the tool %q with the given parameters. Always call the tool to get real data.", step.ToolName),
	}

	paramsJSON, _ := json.Marshal(params)
	userMsg := openai.ChatCompletionMessage{
		Role:    openai.ChatMessageRoleUser,
		Content: fmt.Sprintf("Step intent: %s\nTool: %s\nParams: %s", step.Intent, step.ToolName, string(paramsJSON)),
	}

	messages := []openai.ChatCompletionMessage{systemMsg, userMsg}

	// Call LLM with tools.
	resp, err := s.llmAdapter.ChatWithTools(ctx, messages, tools)
	if err != nil {
		return &StepResult{
			StepIndex: step.Step,
			Success:   false,
			Error:     fmt.Sprintf("LLM call failed: %v", err),
		}, nil
	}

	if len(resp.Choices) == 0 {
		return &StepResult{
			StepIndex: step.Step,
			Success:   false,
			Error:     "LLM returned empty response",
		}, nil
	}

	choice := resp.Choices[0]

	// If the LLM returned text directly (no tool call), return it as the result.
	if choice.Message.Content != "" && len(choice.Message.ToolCalls) == 0 {
		return &StepResult{
			StepIndex: step.Step,
			Success:   true,
			Result:    choice.Message.Content,
		}, nil
	}

	// If no tool calls, this is an incomplete response.
	if len(choice.Message.ToolCalls) == 0 {
		return &StepResult{
			StepIndex: step.Step,
			Success:   true,
			Result:    "",
		}, nil
	}

	// Extract the tool call result.
	// At this point the LLM has returned a tool call request, but we haven't
	// executed the actual tool function. The ChatWithTools call returns the
	// LLM's decision to call a tool, not the tool's output.
	// We need to extract which tool was called and with what arguments.

	toolCall := choice.Message.ToolCalls[0]

	if toolCall.Function.Name == "" {
		return &StepResult{
			StepIndex: step.Step,
			Success:   true,
			Result:    choice.Message.Content,
		}, nil
	}

	// We have a tool call. Return the function name and arguments as the result
	// so the caller (who owns the tool implementations) can execute it.
	resultJSON, _ := json.Marshal(map[string]interface{}{
		"tool":      toolCall.Function.Name,
		"arguments": toolCall.Function.Arguments,
		"content":   choice.Message.Content,
	})

	return &StepResult{
		StepIndex: step.Step,
		Success:   true,
		Result:    string(resultJSON),
	}, nil
}

// resolveParams injects dependency step results from workMemory into the
// current step's parameters.
func (s *AgentService) resolveParams(step PlanStep, workMemory map[string]string) map[string]interface{} {
	params := make(map[string]interface{})
	for k, v := range step.Params {
		params[k] = v
	}

	// If no dependencies, return as-is.
	if len(step.DependsOn) == 0 {
		return params
	}

	// Inject dependency results into params.
	for _, depStep := range step.DependsOn {
		key := fmt.Sprintf("step_%d", depStep)
		value, ok := workMemory[key]
		if !ok {
			continue
		}

		// Try to parse the dependency result as JSON and merge relevant fields.
		var depResult map[string]interface{}
		if err := json.Unmarshal([]byte(value), &depResult); err != nil {
			// Not JSON, store as "previous_result".
			params["previous_result"] = value
			continue
		}

		// Merge common fields from the dependency result.
		for _, field := range []string{"category", "spec", "region", "price", "result"} {
			if v, ok := depResult[field]; ok {
				params[field] = v
			}
		}
	}

	return params
}

// ExecutePlan runs the entire plan step by step, streaming AgentEvents through
// the returned channel. The caller is responsible for converting events to
// SSE format.
func (s *AgentService) ExecutePlan(
	ctx context.Context,
	plan *AgentPlan,
	tools []openai.Tool,
) (<-chan AgentEvent, error) {
	cfg, cfgErr := s.agentConfigSvc.GetAgentConfig(ctx)
	maxRetries := 2
	if cfgErr == nil && cfg != nil && cfg.MaxRetries > 0 && cfg.MaxRetries <= 5 {
		maxRetries = cfg.MaxRetries
	}

	ch := make(chan AgentEvent, 50)

	go func() {
		defer close(ch)

		// Push plan_created event.
		ch <- AgentEvent{Type: "plan_created", Data: plan}

		workMemory := make(map[string]string)

		for i, step := range plan.Steps {
			// Push step_start event.
			ch <- AgentEvent{
				Type: "step_start",
				Data: map[string]interface{}{
					"step": step.Step,
					"tool": step.ToolName,
				},
			}

			// Route to sub-agent if step specifies one.
			var result *StepResult
			var lastErr error

			if step.SubAgentName != "" {
				if subAgent, ok := s.RouteToSubAgent(step); ok {
					result, lastErr = subAgent.Execute(ctx, step, workMemory)
					if lastErr != nil {
						slog.Warn("sub-agent execution error",
							"step", step.Step,
							"sub_agent", step.SubAgentName,
							"error", lastErr,
						)
					}
				} else {
					// Sub-agent not registered; fall through to default execution.
					slog.Warn("sub-agent not found, falling back to default execution",
						"step", step.Step,
						"sub_agent", step.SubAgentName,
					)
				}
			}

			// If no sub-agent or sub-agent not found, execute with retries.
			if result == nil {
				for retry := 0; retry <= maxRetries; retry++ {
					if retry > 0 {
						// Wait 1 second between retries.
						select {
						case <-ctx.Done():
							ch <- AgentEvent{
								Type: "step_failed",
								Data: map[string]interface{}{
									"step":  step.Step,
									"error": "cancelled",
								},
							}
							return
						case <-time.After(1 * time.Second):
						}
					}

					result, lastErr = s.ExecuteStep(ctx, step, workMemory, tools)
					if lastErr != nil {
						slog.Warn("step execution error",
							"step", step.Step,
							"retry", retry,
							"error", lastErr,
						)
						continue
					}

					if result.Success {
						break
					}
				}
			}

			if result == nil || !result.Success {
				errMsg := "unknown error"
				if result != nil {
					errMsg = result.Error
					result.Retries = maxRetries
				}
				ch <- AgentEvent{
					Type: "step_failed",
					Data: map[string]interface{}{
						"step":  step.Step,
						"error": errMsg,
					},
				}

				// Evaluate the failure.
				reflection := s.evaluateFailure(step, result)
				if reflection.Status == "failed" {
					ch <- AgentEvent{Type: "reflection", Data: reflection}
					break
				}

				if reflection.Status == "replan" {
					ch <- AgentEvent{Type: "reflection", Data: reflection}

					// Replan remaining steps.
					newPlan, replanErr := s.Replan(ctx, plan, i, reflection)
					if replanErr != nil {
						slog.Warn("replan failed", "error", replanErr)
						break
					}

					// Append new steps from the replan.
					plan.Steps = append(plan.Steps[:i+1], newPlan.Steps...)
				}
				continue
			}

			// Store result in work memory.
			workMemory[fmt.Sprintf("step_%d", step.Step)] = result.Result

			// Push step_complete event.
			ch <- AgentEvent{
				Type: "step_complete",
				Data: map[string]interface{}{
					"step":   step.Step,
					"result": result.Result,
					"retries": result.Retries,
				},
			}

			// Reflect on the result.
			reflection, evalErr := s.Evaluate(ctx, step, result)
			if evalErr != nil {
				slog.Warn("reflection error", "step", step.Step, "error", evalErr)
				continue
			}

			ch <- AgentEvent{Type: "reflection", Data: reflection}

			switch reflection.Status {
			case "failed":
				// Stop execution entirely.
				return
			case "replan":
				newPlan, replanErr := s.Replan(ctx, plan, i, reflection)
				if replanErr != nil {
					slog.Warn("replan failed", "error", replanErr)
					continue
				}
				// Replace remaining steps with replanned steps.
				plan.Steps = append(plan.Steps[:i+1], newPlan.Steps...)
			case "ok":
				// Continue to next step.
			}
		}

		// Generate summary from work memory.
		summary := s.generateSummary(ctx, plan, workMemory)
		if summary != "" {
			ch <- AgentEvent{
				Type: "summary",
				Data: map[string]interface{}{
					"content": summary,
				},
			}
		}

		// Push the [DONE] marker.
		ch <- AgentEvent{Type: "[DONE]", Data: nil}
	}()

	return ch, nil
}

// generateSummary calls the LLM to produce a natural language summary from
// all step results stored in the work memory.
func (s *AgentService) generateSummary(ctx context.Context, plan *AgentPlan, workMemory map[string]string) string {
	if len(workMemory) == 0 {
		return "任务执行完毕，但未获取到有效数据。"
	}

	// Build a summary of all steps from work memory.
	var stepSummaries []string
	for _, step := range plan.Steps {
		key := fmt.Sprintf("step_%d", step.Step)
		value, ok := workMemory[key]
		if !ok {
			continue
		}
		// Truncate long results.
		if len(value) > 500 {
			value = value[:500] + "..."
		}
		stepSummaries = append(stepSummaries, fmt.Sprintf(
			"Step %d (%s): %s", step.Step, step.Intent, value,
		))
	}

	if len(stepSummaries) == 0 {
		return "任务执行完毕。"
	}

	userContent := fmt.Sprintf(
		"Summarize these task execution results into a concise, professional natural-language response in Chinese. Keep it under 3 paragraphs. Do not use emoji.\n\nResults:\n%s",
		strings.Join(stepSummaries, "\n"),
	)

	messages := []openai.ChatCompletionMessage{
		{
			Role:    openai.ChatMessageRoleSystem,
			Content: "You are a steel industry assistant. Summarize task results concisely in Chinese. Be professional and factual.",
		},
		{Role: openai.ChatMessageRoleUser, Content: userContent},
	}

	resp, err := s.llmAdapter.Chat(ctx, messages)
	if err != nil || len(resp.Choices) == 0 {
		slog.Warn("summary generation failed", "error", err)
		return "任务执行完毕，请查看详细结果。"
	}

	return strings.TrimSpace(resp.Choices[0].Message.Content)
}

