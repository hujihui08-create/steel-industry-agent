// Evaluate assesses the quality of a step result and returns a reflection
// indicating whether to continue, replan, or fail.
func (s *AgentService) Evaluate(
	ctx context.Context,
	step PlanStep,
	result *StepResult,
) (*ReflectionResult, error) {
	if result == nil {
		return &ReflectionResult{Status: "failed", Reason: "no result"}, nil
	}

	// If the step failed outright, it's a failure.
	if !result.Success {
		return &ReflectionResult{
			Status: "failed",
			Reason: result.Error,
		}, nil
	}

	// If the result is empty, ask to replan.
	if result.Result == "" {
		return &ReflectionResult{
			Status:     "replan",
			Reason:     "无数据",
			Suggestion: "尝试扩大搜索范围或调整查询条件",
		}, nil
	}

	// If the result contains signals of no data found, replan.
	noDataSignals := []string{"未查询到", "未找到", "暂无数据", "无相关", "not found", "no data"}
	for _, signal := range noDataSignals {
		if strings.Contains(strings.ToLower(result.Result), strings.ToLower(signal)) {
			return &ReflectionResult{
				Status:     "replan",
				Reason:     "无数据: " + signal,
				Suggestion: "尝试扩大搜索范围或调整查询条件",
			}, nil
		}
	}

	// If the result contains a "source" or "updated_at" field (valid data), it's OK.
	validitySignals := []string{`"source"`, `"updated_at"`, `"price"`, `"prices"`}
	resultLower := strings.ToLower(result.Result)
	for _, signal := range validitySignals {
		if strings.Contains(resultLower, signal) {
			return &ReflectionResult{Status: "ok"}, nil
		}
	}

	// For other cases, do a lightweight LLM check.
	return s.llmEvaluate(ctx, step, result)
}

// llmEvaluate uses a lightweight LLM call to check whether a step result
// is sufficient for the user's intent.
func (s *AgentService) llmEvaluate(
	ctx context.Context,
	step PlanStep,
	result *StepResult,
) (*ReflectionResult, error) {
	prompt := fmt.Sprintf(
		`Evaluate this step execution result.

Step intent: %s
Step result: %s

Is this result sufficient to satisfy the step intent? 
Respond with ONLY a JSON object: {"status": "ok"} or {"status": "replan", "reason": "...", "suggestion": "..."} or {"status": "failed", "reason": "..."}`,
		step.Intent,
		result.Result,
	)

	messages := []openai.ChatCompletionMessage{
		{Role: openai.ChatMessageRoleUser, Content: prompt},
	}

	resp, err := s.llmAdapter.Chat(ctx, messages)
	if err != nil {
		// If LLM evaluation fails, default to "ok" so execution continues.
		slog.Warn("LLM evaluation call failed, defaulting to ok", "error", err)
		return &ReflectionResult{Status: "ok"}, nil
	}

	if len(resp.Choices) == 0 || resp.Choices[0].Message.Content == "" {
		return &ReflectionResult{Status: "ok"}, nil
	}

	raw := strings.TrimSpace(resp.Choices[0].Message.Content)
	// Strip markdown fences.
	raw = strings.TrimPrefix(raw, "```json")
	raw = strings.TrimPrefix(raw, "```")
	raw = strings.TrimSuffix(raw, "```")
	raw = strings.TrimSpace(raw)

	var reflection ReflectionResult
	if err := json.Unmarshal([]byte(raw), &reflection); err != nil {
		slog.Warn("LLM evaluation returned invalid JSON, defaulting to ok",
			"raw", raw,
			"error", err,
		)
		return &ReflectionResult{Status: "ok"}, nil
	}

	// Normalize status.
	switch reflection.Status {
	case "ok", "replan", "failed":
		// Valid.
	default:
		reflection.Status = "ok"
	}

	return &reflection, nil
}

// evaluateFailure creates a reflection result for a failed step without
// calling the LLM.
func (s *AgentService) evaluateFailure(step PlanStep, result *StepResult) *ReflectionResult {
	errMsg := "unknown error"
	if result != nil {
		errMsg = result.Error
	}
	return &ReflectionResult{
		Status: "replan",
		Reason: fmt.Sprintf("Step %d failed: %s", step.Step, errMsg),
	}
}

// Replan adjusts the remaining steps of a plan based on reflection feedback.
func (s *AgentService) Replan(
	ctx context.Context,
	originalPlan *AgentPlan,
	currentStepIndex int,
	reflection *ReflectionResult,
) (*AgentPlan, error) {
	if currentStepIndex < 0 || currentStepIndex >= len(originalPlan.Steps) {
		return &AgentPlan{
			Steps:     nil,
			MaxSteps:  originalPlan.MaxSteps,
			CreatedAt: time.Now(),
		}, nil
	}

	// Get the remaining steps (after currentStepIndex).
	remainingSteps := originalPlan.Steps[currentStepIndex+1:]
	if len(remainingSteps) == 0 {
		return &AgentPlan{
			Steps:     nil,
			MaxSteps:  originalPlan.MaxSteps,
			CreatedAt: time.Now(),
		}, nil
	}

	// Serialize the remaining steps for the LLM.
	remainingJSON, _ := json.Marshal(remainingSteps)

	prompt := fmt.Sprintf(
		`Step %d failed or needs adjustment. 

Failure reason: %s
Suggestion: %s

Remaining steps:
%s

Adjust the remaining steps to account for this failure. Remove unnecessary steps, add new ones if needed, and renumber them starting from step %d.

Return ONLY a JSON array of adjusted steps.`,
		originalPlan.Steps[currentStepIndex].Step,
		reflection.Reason,
		reflection.Suggestion,
		string(remainingJSON),
		originalPlan.Steps[currentStepIndex].Step+1,
	)

	messages := []openai.ChatCompletionMessage{
		{
			Role:    openai.ChatMessageRoleSystem,
			Content: "You are a task replanner. Adjust remaining execution steps based on feedback. Return ONLY a valid JSON array of step objects.",
		},
		{Role: openai.ChatMessageRoleUser, Content: prompt},
	}

	resp, err := s.llmAdapter.Chat(ctx, messages)
	if err != nil {
		slog.Warn("replan LLM call failed", "error", err)
		return &AgentPlan{Steps: nil, MaxSteps: originalPlan.MaxSteps, CreatedAt: time.Now()}, nil
	}

	if len(resp.Choices) == 0 || resp.Choices[0].Message.Content == "" {
		return &AgentPlan{Steps: nil, MaxSteps: originalPlan.MaxSteps, CreatedAt: time.Now()}, nil
	}

	raw := strings.TrimSpace(resp.Choices[0].Message.Content)
	raw = strings.TrimPrefix(raw, "```json")
	raw = strings.TrimPrefix(raw, "```")
	raw = strings.TrimSuffix(raw, "```")
	raw = strings.TrimSpace(raw)

	// Parse as either a single-step object or an array.
	var newSteps []PlanStep
	if err := json.Unmarshal([]byte(raw), &newSteps); err != nil {
		// Try parsing as a single object.
		var single PlanStep
		if err2 := json.Unmarshal([]byte(raw), &single); err2 != nil {
			slog.Warn("replan returned invalid JSON, dropping remaining steps",
				"raw", raw,
				"error", err,
			)
			return &AgentPlan{Steps: nil, MaxSteps: originalPlan.MaxSteps, CreatedAt: time.Now()}, nil
		}
		newSteps = []PlanStep{single}
	}

	// Enforce max steps.
	if len(newSteps) > originalPlan.MaxSteps {
		newSteps = newSteps[:originalPlan.MaxSteps]
	}

	return &AgentPlan{
		Steps:     newSteps,
		MaxSteps:  originalPlan.MaxSteps,
		CreatedAt: time.Now(),
	}, nil
}

